<?php
namespace MiB;

/** System tables (users, groups, rights, audit, locks, notifications) created on first run in the main database. */
class Schema
{
    const VERSION = 4;

    public static function prefix()
    {
        return isset(App::$i->config['systemPrefix']) ? App::$i->config['systemPrefix'] : 'mc_';
    }

    public static function t($name)
    {
        return self::prefix() . $name;
    }

    private static function marker()
    {
        $d = App::$i->setting('uploadDir', 'files');
        $dir = $d[0] === '/' ? $d : App::$i->root . '/' . $d;
        return $dir . '/.mc_schema_' . self::VERSION . '_' . md5(json_encode(App::$i->config['connections'][App::$i->config['defaultConnection']]));
    }

    public static function needed()
    {
        $c = App::$i->config;
        $s = $c['security'];
        return ($s['enabled'] && $s['mode'] === 'database') || !empty($c['settings']['audit']) || !empty($c['settings']['recordLocking']) || !empty($c['settings']['webBuilder']['enabled'])
            || (!empty($s['dynamicPermissions']) && $s['enabled'])
            || ($s['enabled'] && (!isset($c['settings']['notifications']) || $c['settings']['notifications'] !== false));
    }

    public static function ensure()
    {
        if (!self::needed() || is_file(self::marker())) return;
        $db = App::$i->db();
        foreach (self::ddl($db) as $name => $sql) {
            if (self::exists($db, self::t($name))) continue;
            foreach ((array)$sql as $s) $db->pdo->exec($s);
        }
        self::seed($db);
        @file_put_contents(self::marker(), date('c'));
    }

    public static function exists(Db $db, $table)
    {
        try { $db->query('SELECT 1 FROM ' . $db->table($table) . ' WHERE 1=0'); return true; } catch (\Throwable $e) { return false; }
    }

    private static function ddl(Db $db)
    {
        $d = $db->driver;
        $id = ['mysql' => 'INT AUTO_INCREMENT PRIMARY KEY', 'pgsql' => 'SERIAL PRIMARY KEY', 'sqlsrv' => 'INT IDENTITY(1,1) PRIMARY KEY',
            'oracle' => 'NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'sqlite' => 'INTEGER PRIMARY KEY AUTOINCREMENT'][$d];
        $vc = function ($n) use ($d) { return ($d === 'oracle' ? 'VARCHAR2' : ($d === 'sqlsrv' ? 'NVARCHAR' : 'VARCHAR')) . "($n)"; };
        $text = ['mysql' => 'LONGTEXT', 'pgsql' => 'TEXT', 'sqlsrv' => 'NVARCHAR(MAX)', 'oracle' => 'CLOB', 'sqlite' => 'TEXT'][$d];
        $ts = ['mysql' => 'DATETIME', 'pgsql' => 'TIMESTAMP', 'sqlsrv' => 'DATETIME2', 'oracle' => 'TIMESTAMP', 'sqlite' => 'TEXT'][$d];
        $int = $d === 'oracle' ? 'NUMBER(10)' : 'INT';
        $q = function ($n) use ($db) { return $db->table(self::t($n)); };
        $c = function ($n) use ($db) { return $db->q($n); };
        $engine = $d === 'mysql' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4' : '';
        return [
            'users' => 'CREATE TABLE ' . $q('users') . " ({$c('id')} $id, {$c('username')} {$vc(150)} NOT NULL, {$c('password')} {$vc(255)}, {$c('email')} {$vc(255)}, "
                . "{$c('fullname')} {$vc(255)}, {$c('active')} $int DEFAULT 1, {$c('verified')} $int DEFAULT 1, {$c('provider')} {$vc(50)}, {$c('api_key')} {$vc(64)}, "
                . "{$c('token')} {$vc(64)}, {$c('token_expires')} $ts, {$c('failed')} $int DEFAULT 0, {$c('locked_until')} $ts, {$c('totp_secret')} {$vc(64)}, "
                . "{$c('created_at')} $ts, {$c('last_login')} $ts, CONSTRAINT " . $c(self::t('users_uq')) . " UNIQUE ({$c('username')}))$engine",
            'groups' => 'CREATE TABLE ' . $q('groups') . " ({$c('id')} {$vc(50)} NOT NULL PRIMARY KEY, {$c('label')} {$vc(200)}, {$c('is_admin')} $int DEFAULT 0)$engine",
            'members' => 'CREATE TABLE ' . $q('members') . " ({$c('username')} {$vc(150)} NOT NULL, {$c('group_id')} {$vc(50)} NOT NULL, PRIMARY KEY ({$c('username')}, {$c('group_id')}))$engine",
            'rights' => 'CREATE TABLE ' . $q('rights') . " ({$c('group_id')} {$vc(50)} NOT NULL, {$c('table_name')} {$vc(150)} NOT NULL, {$c('rights')} {$vc(20)}, PRIMARY KEY ({$c('group_id')}, {$c('table_name')}))$engine",
            'audit' => 'CREATE TABLE ' . $q('audit') . " ({$c('id')} $id, {$c('ts')} $ts, {$c('username')} {$vc(150)}, {$c('ip')} {$vc(64)}, {$c('table_name')} {$vc(150)}, "
                . "{$c('action')} {$vc(20)}, {$c('keys_json')} {$vc(500)}, {$c('old_json')} $text, {$c('new_json')} $text)$engine",
            'reports' => 'CREATE TABLE ' . $q('reports') . " ({$c('id')} $id, {$c('owner')} {$vc(150)}, {$c('kind')} {$vc(10)}, {$c('title')} {$vc(200)}, {$c('table_name')} {$vc(150)}, "
                . "{$c('def')} $text, {$c('shared')} $int DEFAULT 0, {$c('created_at')} $ts)$engine",
            'locks' => 'CREATE TABLE ' . $q('locks') . " ({$c('table_name')} {$vc(150)} NOT NULL, {$c('keys_json')} {$vc(255)} NOT NULL, {$c('username')} {$vc(150)}, {$c('ts')} $ts, "
                . "PRIMARY KEY ({$c('table_name')}, {$c('keys_json')}))$engine",
            'notifications' => 'CREATE TABLE ' . $q('notifications') . " ({$c('id')} $id, {$c('username')} {$vc(150)}, {$c('title')} {$vc(255)}, {$c('message')} $text, "
                . "{$c('icon')} {$vc(50)}, {$c('url')} {$vc(500)}, {$c('new_window')} $int DEFAULT 0, {$c('created_at')} $ts, {$c('expires_at')} $ts)$engine",
            'searches' => 'CREATE TABLE ' . $q('searches') . " ({$c('id')} $id, {$c('username')} {$vc(150)}, {$c('table_name')} {$vc(150)}, {$c('title')} {$vc(200)}, "
                . "{$c('query_json')} $text, {$c('shared')} $int DEFAULT 0, {$c('created_at')} $ts)$engine",
            'notif_seen' => 'CREATE TABLE ' . $q('notif_seen') . " ({$c('username')} {$vc(150)} NOT NULL PRIMARY KEY, {$c('last_id')} $int DEFAULT 0)$engine",
        ];
    }

    /** Groups and rights from the designer, inserted once. */
    private static function seed(Db $db)
    {
        $sec = App::$i->config['security'];
        if ((int)$db->value('SELECT COUNT(*) FROM ' . $db->table(self::t('groups'))) > 0) return;
        foreach ($sec['groups'] as $g) {
            $db->insert(self::t('groups'), ['id' => $g['id'], 'label' => App::$i->label($g['label'], $g['id']), 'is_admin' => !empty($g['admin']) ? 1 : 0]);
        }
        foreach ($sec['permissions'] as $group => $tables) {
            foreach ($tables as $table => $rights) $db->insert(self::t('rights'), ['group_id' => $group, 'table_name' => $table, 'rights' => $rights]);
        }
    }
}
