<?php
namespace MiB;

/** System tables (users, groups, rights, audit, locks, notifications) created on first run in the main database. */
class Schema
{
    const VERSION = 7;

    public static function prefix()
    {
        return isset(App::$i->config['systemPrefix']) ? App::$i->config['systemPrefix'] : 'mc_';
    }

    public static function t($name)
    {
        return self::prefix() . $name;
    }

    private static function marker()
    {
        $d = App::$i->setting('uploadDir', 'files');
        $dir = $d[0] === '/' ? $d : App::$i->root . '/' . $d;
        return $dir . '/.mc_schema_' . self::VERSION . '_' . md5(json_encode(App::$i->config['connections'][App::$i->config['defaultConnection']]));
    }

    public static function needed()
    {
        $c = App::$i->config;
        $s = $c['security'];
        return ($s['enabled'] && $s['mode'] === 'database') || !empty($c['settings']['audit']) || !empty($c['settings']['recordLocking']) || !empty($c['settings']['webBuilder']['enabled'])
            || (!empty($s['dynamicPermissions']) && $s['enabled'])
            || ($s['enabled'] && (!isset($c['settings']['notifications']) || $c['settings']['notifications'] !== false))
            || ($s['enabled'] && (!isset($c['settings']['savedSearches']) || $c['settings']['savedSearches'] !== false))
            || !empty($c['settings']['tasks']);
    }

    public static function ensure()
    {
        if (!self::needed() || is_file(self::marker())) return;
        $db = App::$i->db();
        foreach (self::ddl($db) as $name => $sql) {
            if (self::exists($db, self::t($name))) continue;
            foreach ((array)$sql as $s) $db->pdo->exec($s);
        }
        self::seed($db);
        @file_put_contents(self::marker(), date('c'));
    }

    public static function exists(Db $db, $table)
    {
        try { $db->query('SELECT 1 FROM ' . $db->table($table) . ' WHERE 1=0'); return true; } catch (\Throwable $e) { return false; }
    }

    private static function ddl(Db $db)
    {
        $d = $db->driver;
        $fab = $db->fabric;
        // Fabric: BIGINT IDENTITY (no seed), keys and UNIQUE as NOT ENFORCED table constraints, no NVARCHAR, explicit datetime precision
        $id = $fab ? 'BIGINT IDENTITY NOT NULL' : ['mysql' => 'INT AUTO_INCREMENT PRIMARY KEY', 'pgsql' => 'SERIAL PRIMARY KEY', 'sqlsrv' => 'INT IDENTITY(1,1) PRIMARY KEY',
            'oracle' => 'NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'sqlite' => 'INTEGER PRIMARY KEY AUTOINCREMENT'][$d];
        $vc = function ($n) use ($db) { return $db->varchar($n); };
        $text = ['mysql' => 'LONGTEXT', 'pgsql' => 'TEXT', 'sqlsrv' => $fab ? 'VARCHAR(MAX)' : 'NVARCHAR(MAX)', 'oracle' => 'CLOB', 'sqlite' => 'TEXT'][$d];
        $ts = ['mysql' => 'DATETIME', 'pgsql' => 'TIMESTAMP', 'sqlsrv' => $fab ? 'DATETIME2(6)' : 'DATETIME2', 'oracle' => 'TIMESTAMP', 'sqlite' => 'TEXT'][$d];
        $pk = $fab ? ' NOT NULL' : ' NOT NULL PRIMARY KEY';                 // inline single-column key
        $tpk = function (array $cols) use ($db, $fab) { return $fab ? $db->primaryKey($cols) : ''; }; // Fabric: key as a trailing constraint
        $idpk = $tpk(['id']);
        $uq = $fab ? ' NONCLUSTERED' : '';
        $ne = $fab ? ' NOT ENFORCED' : '';
        $pkc = function (array $cols) use ($db) { return $db->primaryKey($cols); };   // composite key clause, ", PRIMARY KEY (...)"
        $int = $d === 'oracle' ? 'NUMBER(10)' : 'INT';
        $q = function ($n) use ($db) { return $db->table(self::t($n)); };
        $c = function ($n) use ($db) { return $db->q($n); };
        $engine = $d === 'mysql' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4' : '';
        return [
            'users' => 'CREATE TABLE ' . $q('users') . " ({$c('id')} $id, {$c('username')} {$vc(150)} NOT NULL, {$c('password')} {$vc(255)}, {$c('email')} {$vc(255)}, "
                . "{$c('fullname')} {$vc(255)}, {$c('active')} $int DEFAULT 1, {$c('verified')} $int DEFAULT 1, {$c('provider')} {$vc(50)}, {$c('api_key')} {$vc(64)}, "
                . "{$c('token')} {$vc(64)}, {$c('token_expires')} $ts, {$c('failed')} $int DEFAULT 0, {$c('locked_until')} $ts, {$c('totp_secret')} {$vc(64)}, "
                . "{$c('created_at')} $ts, {$c('last_login')} $ts{$idpk}, CONSTRAINT " . $c(self::t('users_uq')) . " UNIQUE{$uq} ({$c('username')}){$ne})$engine",
            'groups' => 'CREATE TABLE ' . $q('groups') . " ({$c('id')} {$vc(50)}$pk, {$c('label')} {$vc(200)}, {$c('is_admin')} $int DEFAULT 0{$tpk(['id'])})$engine",
            'members' => 'CREATE TABLE ' . $q('members') . " ({$c('username')} {$vc(150)} NOT NULL, {$c('group_id')} {$vc(50)} NOT NULL{$pkc(['username', 'group_id'])})$engine",
            'rights' => 'CREATE TABLE ' . $q('rights') . " ({$c('group_id')} {$vc(50)} NOT NULL, {$c('table_name')} {$vc(150)} NOT NULL, {$c('rights')} {$vc(20)}{$pkc(['group_id', 'table_name'])})$engine",
            'audit' => 'CREATE TABLE ' . $q('audit') . " ({$c('id')} $id, {$c('ts')} $ts, {$c('username')} {$vc(150)}, {$c('ip')} {$vc(64)}, {$c('table_name')} {$vc(150)}, "
                . "{$c('action')} {$vc(20)}, {$c('keys_json')} {$vc(500)}, {$c('old_json')} $text, {$c('new_json')} $text{$idpk})$engine",
            'reports' => 'CREATE TABLE ' . $q('reports') . " ({$c('id')} $id, {$c('owner')} {$vc(150)}, {$c('kind')} {$vc(10)}, {$c('title')} {$vc(200)}, {$c('table_name')} {$vc(150)}, "
                . "{$c('def')} $text, {$c('shared')} $int DEFAULT 0, {$c('created_at')} $ts{$idpk})$engine",
            'locks' => 'CREATE TABLE ' . $q('locks') . " ({$c('table_name')} {$vc(150)} NOT NULL, {$c('keys_json')} {$vc(255)} NOT NULL, {$c('username')} {$vc(150)}, {$c('ts')} $ts, "
                . ltrim($pkc(['table_name', 'keys_json']), ', ') . ")$engine",
            'notifications' => 'CREATE TABLE ' . $q('notifications') . " ({$c('id')} $id, {$c('username')} {$vc(150)}, {$c('title')} {$vc(255)}, {$c('message')} $text, "
                . "{$c('icon')} {$vc(50)}, {$c('url')} {$vc(500)}, {$c('new_window')} $int DEFAULT 0, {$c('created_at')} $ts, {$c('expires_at')} $ts{$idpk})$engine",
            'searches' => 'CREATE TABLE ' . $q('searches') . " ({$c('id')} $id, {$c('username')} {$vc(150)}, {$c('table_name')} {$vc(150)}, {$c('title')} {$vc(200)}, "
                . "{$c('query_json')} $text, {$c('shared')} $int DEFAULT 0, {$c('created_at')} $ts{$idpk})$engine",
            'tasks' => 'CREATE TABLE ' . $q('tasks') . " ({$c('name')} {$vc(100)}$pk, {$c('last_run')} $ts, {$c('ok')} $int DEFAULT 0, "
                . "{$c('message')} $text, {$c('duration')} " . ['mysql' => 'DECIMAL(12,3)', 'pgsql' => 'NUMERIC(12,3)', 'sqlsrv' => 'DECIMAL(12,3)', 'oracle' => 'NUMBER(12,3)', 'sqlite' => 'REAL'][$d] . $tpk(['name']) . ")$engine",
            'phones' => 'CREATE TABLE ' . $q('phones') . " ({$c('username')} {$vc(150)}$pk, {$c('phone')} {$vc(50)}{$tpk(['username'])})$engine",
            'remember' => 'CREATE TABLE ' . $q('remember') . " ({$c('selector')} {$vc(24)}$pk, {$c('username')} {$vc(150)}, {$c('hash')} {$vc(64)}, {$c('expires')} $ts{$tpk(['selector'])})$engine",
            'notif_seen' => 'CREATE TABLE ' . $q('notif_seen') . " ({$c('username')} {$vc(150)}$pk, {$c('last_id')} $int DEFAULT 0{$tpk(['username'])})$engine",
        ];
    }

    /**
     * Inserts a user and returns its id. Fabric Warehouse does not enforce UNIQUE (username), so there the application does:
     * the name is checked before the insert and, if two sign-ups raced past that check, the row with the lowest id wins.
     * On the other engines the UNIQUE constraint does the job and this is a plain insert.
     * @throws DuplicateKey
     */
    public static function insertUser(Db $db, array $vals)
    {
        if (!$db->fabric) return $db->insert(self::t('users'), $vals, 'id');
        self::requireFreeUsername($db, $vals['username'], null);
        $id = $db->insert(self::t('users'), $vals, 'id');
        self::keepFirstUser($db, $vals['username'], $id);
        return $id;
    }

    /** Fabric only: refuses a username already used by another user (except $exceptId, the user being edited). @throws DuplicateKey */
    public static function requireFreeUsername(Db $db, $username, $exceptId)
    {
        if (!$db->fabric) return;
        $sql = 'SELECT COUNT(*) FROM ' . $db->table(self::t('users')) . ' WHERE ' . $db->q('username') . ' = ?';
        $params = [$username];
        if ($exceptId !== null) { $sql .= ' AND ' . $db->q('id') . ' <> ?'; $params[] = $exceptId; }
        if ((int)$db->value($sql, $params) > 0) throw new DuplicateKey('Username already in use');
    }

    /** After an insert: when the same username now exists on a row with a lower id, the new row ($id) is removed. @throws DuplicateKey */
    public static function keepFirstUser(Db $db, $username, $id)
    {
        $first = $db->value('SELECT MIN(' . $db->q('id') . ') FROM ' . $db->table(self::t('users')) . ' WHERE ' . $db->q('username') . ' = ?', [$username]);
        if ($id !== null && $first !== null && (string)$first !== (string)$id) {
            $db->delete(self::t('users'), ['id' => $id]);
            throw new DuplicateKey('Username already in use');
        }
    }

    /** Groups and rights from the designer, inserted once. */
    private static function seed(Db $db)
    {
        $sec = App::$i->config['security'];
        if ((int)$db->value('SELECT COUNT(*) FROM ' . $db->table(self::t('groups'))) > 0) return;
        foreach ($sec['groups'] as $g) {
            $db->insert(self::t('groups'), ['id' => $g['id'], 'label' => App::$i->label($g['label'], $g['id']), 'is_admin' => !empty($g['admin']) ? 1 : 0]);
        }
        foreach ($sec['permissions'] as $group => $tables) {
            foreach ($tables as $table => $rights) $db->insert(self::t('rights'), ['group_id' => $group, 'table_name' => $table, 'rights' => $rights]);
        }
    }
}

/** What a UNIQUE violation looks like to the callers that already catch PDOException (SQLSTATE 23000). */
class DuplicateKey extends \PDOException
{
    protected $code = '23000';
}
