'use strict';
// DDL for the "Tables and queries" screen: create/alter/drop tables and SQL scripts that
// recreate tables (structure and optionally data) on another server, for the five dialects.

const TYPES = ['int', 'bigint', 'decimal', 'float', 'varchar', 'text', 'date', 'datetime', 'time', 'bool', 'blob'];

function quote(dialect, name) {
  if (dialect === 'mysql') return '`' + String(name).replace(/`/g, '``') + '`';
  if (dialect === 'sqlsrv') return '[' + String(name).replace(/]/g, ']]') + ']';
  return '"' + String(name).replace(/"/g, '""') + '"';
}

// Abstract column type -> SQL type of the dialect.
function sqlType(dialect, col) {
  const size = Number(col.size) || 0;
  const scale = Number(col.scale) || 0;
  switch (col.type) {
    case 'int': return dialect === 'oracle' ? 'NUMBER(10)' : 'INT';
    case 'bigint': return dialect === 'oracle' ? 'NUMBER(19)' : dialect === 'sqlite' ? 'INTEGER' : 'BIGINT';
    case 'decimal': return dialect === 'oracle' ? `NUMBER(${size || 18},${scale})` : `DECIMAL(${size || 18},${scale})`;
    case 'float': return { mysql: 'DOUBLE', pgsql: 'DOUBLE PRECISION', sqlsrv: 'FLOAT', oracle: 'BINARY_DOUBLE', sqlite: 'REAL' }[dialect];
    case 'varchar': return dialect === 'oracle' ? `VARCHAR2(${size || 255})` : dialect === 'sqlsrv' ? `NVARCHAR(${size || 255})` : `VARCHAR(${size || 255})`;
    case 'text': return { mysql: 'LONGTEXT', pgsql: 'TEXT', sqlsrv: 'NVARCHAR(MAX)', oracle: 'CLOB', sqlite: 'TEXT' }[dialect];
    case 'date': return 'DATE';
    case 'datetime': return { mysql: 'DATETIME', pgsql: 'TIMESTAMP', sqlsrv: 'DATETIME2', oracle: 'TIMESTAMP', sqlite: 'TEXT' }[dialect];
    case 'time': return { mysql: 'TIME', pgsql: 'TIME', sqlsrv: 'TIME', oracle: 'VARCHAR2(8)', sqlite: 'TEXT' }[dialect];
    case 'bool': return { mysql: 'TINYINT(1)', pgsql: 'BOOLEAN', sqlsrv: 'BIT', oracle: 'NUMBER(1)', sqlite: 'INTEGER' }[dialect];
    case 'blob': return { mysql: 'LONGBLOB', pgsql: 'BYTEA', sqlsrv: 'VARBINARY(MAX)', oracle: 'BLOB', sqlite: 'BLOB' }[dialect];
  }
  return col.type; // raw SQL type
}

// Database column (from describeTable) -> abstract column for the editor.
function fromDb(c) {
  const t = String(c.dbType || '').toLowerCase();
  const m = t.match(/\((\d+)(?:,\s*(\d+))?\)/);
  let type = c.type === 'int' ? (/big/.test(t) ? 'bigint' : 'int') : c.type === 'decimal' ? (/float|double|real/.test(t) ? 'float' : 'decimal') : c.type === 'string' ? 'varchar' : c.type === 'binary' ? 'blob' : c.type;
  if (!TYPES.includes(type)) type = 'varchar';
  return { name: c.name, type, size: m ? Number(m[1]) : (c.length || ''), scale: m && m[2] ? Number(m[2]) : '', pk: !!c.pk, autoInc: !!c.autoInc, nullable: !!c.nullable, default: c.default == null ? '' : String(c.default), orig: c.name };
}

function columnSql(dialect, col, opts = {}) {
  const q = (n) => quote(dialect, n);
  let s = `${q(col.name)} `;
  if (col.autoInc && opts.inCreate) {
    s += { mysql: `${sqlType(dialect, col)} AUTO_INCREMENT`, pgsql: col.type === 'bigint' ? 'BIGSERIAL' : 'SERIAL', sqlsrv: `${sqlType(dialect, col)} IDENTITY(1,1)`,
      oracle: `${sqlType(dialect, col)} GENERATED BY DEFAULT AS IDENTITY`, sqlite: 'INTEGER' }[dialect];
  } else s += sqlType(dialect, col);
  if (!col.nullable || col.pk) s += ' NOT NULL';
  if (col.default !== '' && col.default != null && !col.autoInc) {
    const d = String(col.default);
    s += ' DEFAULT ' + (/^-?\d+(\.\d+)?$/.test(d) || /^(CURRENT_TIMESTAMP|NULL|now\(\))$/i.test(d) ? d : `'${d.replace(/'/g, "''")}'`);
  }
  return s;
}

function createTable(dialect, table, cols) {
  if (!table) throw new Error('Nome tabella mancante');
  if (!cols.length) throw new Error('La tabella non ha campi');
  const pk = cols.filter((c) => c.pk);
  const sqliteAuto = dialect === 'sqlite' && pk.length === 1 && pk[0].autoInc;
  const lines = cols.map((c) => (sqliteAuto && c.pk ? `${quote(dialect, c.name)} INTEGER PRIMARY KEY AUTOINCREMENT` : columnSql(dialect, c, { inCreate: true })));
  if (pk.length && !sqliteAuto) lines.push(`PRIMARY KEY (${pk.map((c) => quote(dialect, c.name)).join(', ')})`);
  return `CREATE TABLE ${quote(dialect, table)} (\n  ${lines.join(',\n  ')}\n)${dialect === 'mysql' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4' : ''}`;
}

// Statements to go from `before` to `after` columns (orig = previous name).
function alterTable(dialect, table, before, after) {
  const q = (n) => quote(dialect, n);
  const T = q(table);
  const out = [];
  const byOrig = new Map(before.map((c) => [c.name, c]));
  // orig = name of the column before editing ('' or null for new columns).
  const origOf = (a) => (a.orig !== undefined ? a.orig : (byOrig.has(a.name) ? a.name : null));
  for (const c of before) if (!after.some((a) => origOf(a) === c.name)) out.push(`ALTER TABLE ${T} DROP COLUMN ${q(c.name)}`);
  for (const a of after) {
    const old = origOf(a) ? byOrig.get(origOf(a)) : null;
    if (!old) {
      out.push(dialect === 'sqlsrv' || dialect === 'oracle' ? `ALTER TABLE ${T} ADD ${columnSql(dialect, a)}` : `ALTER TABLE ${T} ADD COLUMN ${columnSql(dialect, a)}`);
      continue;
    }
    if (a.name !== old.name) {
      out.push(dialect === 'sqlsrv' ? `EXEC sp_rename '${table}.${old.name}', '${a.name}', 'COLUMN'` : `ALTER TABLE ${T} RENAME COLUMN ${q(old.name)} TO ${q(a.name)}`);
    }
    const changed = ['type', 'size', 'scale', 'nullable', 'default'].some((k) => String(a[k] ?? '') !== String(old[k] ?? ''));
    if (!changed) continue;
    if (dialect === 'mysql') out.push(`ALTER TABLE ${T} MODIFY ${columnSql(dialect, a, { inCreate: a.autoInc })}`);
    else if (dialect === 'pgsql') {
      out.push(`ALTER TABLE ${T} ALTER COLUMN ${q(a.name)} TYPE ${sqlType(dialect, a)}`);
      out.push(`ALTER TABLE ${T} ALTER COLUMN ${q(a.name)} ${a.nullable && !a.pk ? 'DROP' : 'SET'} NOT NULL`);
    } else if (dialect === 'sqlsrv') out.push(`ALTER TABLE ${T} ALTER COLUMN ${q(a.name)} ${sqlType(dialect, a)}${a.nullable && !a.pk ? ' NULL' : ' NOT NULL'}`);
    else if (dialect === 'oracle') out.push(`ALTER TABLE ${T} MODIFY (${q(a.name)} ${sqlType(dialect, a)}${a.nullable && !a.pk ? ' NULL' : ' NOT NULL'})`);
    else throw new Error('SQLite non permette di modificare il tipo di una colonna esistente: crea una nuova tabella');
  }
  const pkB = before.filter((c) => c.pk).map((c) => c.name).join(',');
  const pkA = after.filter((c) => c.pk).map((c) => c.name).join(',');
  if (pkB !== pkA && dialect !== 'sqlite') {
    if (pkB) out.push(dialect === 'mysql' ? `ALTER TABLE ${T} DROP PRIMARY KEY` : `-- rimuovi la chiave primaria esistente di ${table} prima di continuare`);
    if (pkA) out.push(`ALTER TABLE ${T} ADD PRIMARY KEY (${after.filter((c) => c.pk).map((c) => q(c.name)).join(', ')})`);
  }
  return out;
}

function dropTable(dialect, table) {
  return `DROP TABLE ${quote(dialect, table)}`;
}

function literal(dialect, v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (v instanceof Date) return `'${v.toISOString().slice(0, 19).replace('T', ' ')}'`;
  if (Buffer.isBuffer(v)) return dialect === 'pgsql' ? `'\\x${v.toString('hex')}'` : dialect === 'mysql' || dialect === 'sqlite' ? `X'${v.toString('hex')}'` : `0x${v.toString('hex')}`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

// SQL script recreating `tables` ([{name, columns (abstract), rows?}]) in `dialect`.
function script(dialect, tables, opts = {}) {
  const out = [`-- Script generato da MiB-Crude il ${new Date().toISOString().slice(0, 19).replace('T', ' ')} (destinazione: ${dialect})`, ''];
  for (const t of tables) {
    if (opts.drop) out.push(`${dialect === 'mysql' || dialect === 'pgsql' || dialect === 'sqlite' ? `DROP TABLE IF EXISTS ${quote(dialect, t.name)}` : dropTable(dialect, t.name)};`);
    out.push(createTable(dialect, t.name, t.columns) + ';', '');
    if (t.rows && t.rows.length) {
      const cols = t.columns.map((c) => quote(dialect, c.name)).join(', ');
      for (const r of t.rows) out.push(`INSERT INTO ${quote(dialect, t.name)} (${cols}) VALUES (${t.columns.map((c) => literal(dialect, r[c.name])).join(', ')});`);
      out.push('');
    }
  }
  return out.join('\n');
}

module.exports = { TYPES, quote, sqlType, fromDb, createTable, alterTable, dropTable, script };
