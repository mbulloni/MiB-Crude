'use strict';
// Material Design Admin (AngularJS 1 + Angular Material + Bootstrap 3). The template builds its
// header and sidebar with AngularJS: MiB-Crude writes the same markup in PHP and keeps only the
// template's own styles from dist/styles/main.css, which concatenates angular-material.min.css,
// bootstrap.css, ui.css and app.css (one per line): the first two are left out.
const fs = require('node:fs');
const path = require('node:path');

// Colour skins of the template's customizer (logo / header / sidebar).
const SKINS = {
  dark: ['Barra laterale scura', { logo: 'bg-dark', header: 'bg-white', nav: 'bg-dark' }],
  primary: ['Logo blu, barra laterale scura', { logo: 'bg-primary', header: 'bg-white', nav: 'bg-dark' }],
  light: ['Intestazione blu, barra laterale chiara', { logo: 'bg-primary', header: 'bg-primary', nav: 'bg-white' }],
  horizontal: ['Menu orizzontale', { logo: 'bg-dark', header: 'bg-white', nav: 'bg-dark', horizontal: true }],
};

/** ui.css + app.css from the built main.css (the lines after the Bootstrap banner). */
function templateCss(mainCss) {
  const lines = mainCss.split('\n');
  const boot = lines.findIndex((l) => /Bootstrap v3/.test(l));
  if (boot < 0) throw new Error('main.css: Bootstrap 3 non trovato, struttura del template cambiata');
  // Bootstrap is the first long line after its banner; ui.css and app.css follow.
  let i = boot;
  while (i < lines.length && lines[i].length < 1000) i++;
  return lines.slice(i + 1).filter((l) => l.trim()).join('\n');
}

module.exports = {
  id: 'material',
  name: 'Material Design Admin',
  dir: 'material',
  SKINS,
  templateCss,
  /** Options the users can change in the app (same CSS, other classes). */
  choices() {
    return [{ key: 'skin', label: { it: 'Colori', en: 'Colours' }, values: Object.entries(SKINS).map(([id, [label, set]]) => ({ id, label: { it: label }, set: { skin: id, horizontal: false, ...set } })) }];
  },
  detect(dir) {
    const main = path.join(dir, 'styles', 'main.css');
    if (path.basename(dir) !== 'dist' || !fs.existsSync(main) || !fs.existsSync(path.join(dir, 'app', 'layout', 'sidebar.html'))) return null;
    const pkg = path.basename(path.dirname(dir)); // Material-AngularJS-Admin-Full-Package v1.5.0
    if (!/material/i.test(pkg)) return null;
    const version = (pkg.match(/v([\d.]+)/) || [])[1] || '1';
    return {
      root: dir, name: `Material Admin ${version}`, slug: `material${version.split('.')[0]}`,
      variants: Object.entries(SKINS).map(([id, [label]]) => ({ id, label })),
    };
  },
  install(root, variant, dest) {
    fs.mkdirSync(path.join(dest, 'css'), { recursive: true });
    const css = templateCss(fs.readFileSync(path.join(root, 'styles', 'main.css'), 'utf8'));
    fs.writeFileSync(path.join(dest, 'css', 'material.mc.css'), `/* Material Admin: ui.css + app.css without Angular Material and Bootstrap 3 — generated by MiB-Crude */\n${css}`);
    return {
      bootstrap: 3,
      css: ['assets/css/material.mc.css', 'layouts/theme.css'],
      jsFirst: [],
      js: ['layouts/theme.js'],
      providesBootstrap: false, providesJquery: false,
      fonts: 'https://fonts.googleapis.com/css?family=Roboto:300,400,500,700',
      options: { skin: variant, ...SKINS[variant][1] },
    };
  },
};
