'use strict';
// ThemePixels Slim (Bootstrap 4.1): slim.css bundles Bootstrap 4, which is removed (the pages use
// Bootstrap 5); the template's overrides, layout and helper classes are kept. The dark skin
// (slim.one.css) is limited to the app's dark mode, so one theme follows the light/dark switch.
const fs = require('node:fs');
const path = require('node:path');
const C = require('../css.cjs');

// slim.css sections: 3 Bootstrap overrides, 5 template layout, 7 helper classes
// (2 Bootstrap 4, 4 vendor plugins and 6 demo pages are left out).
const KEEP = [3, 5, 7];

module.exports = {
  id: 'slim',
  name: 'Slim (ThemePixels)',
  dir: 'slim',
  detect(dir) {
    if (!fs.existsSync(path.join(dir, 'css', 'slim.css')) || !fs.existsSync(path.join(dir, 'sidebar', 'blank.html'))) return null;
    const head = fs.readFileSync(path.join(dir, 'css', 'slim.css'), 'utf8').slice(0, 200);
    const version = (head.match(/Slim v([\d.]+)/) || [])[1] || '1';
    return {
      root: dir, name: `Slim ${version}`, slug: `slim${version.split('.')[0]}`,
      variants: [{ id: 'sidebar', label: 'Menu laterale' }, { id: 'horizontal', label: 'Menu orizzontale' }],
    };
  },
  install(root, variant, dest) {
    const css = fs.readFileSync(path.join(root, 'css', 'slim.css'), 'utf8');
    fs.mkdirSync(path.join(dest, 'css'), { recursive: true });
    fs.writeFileSync(path.join(dest, 'css', 'slim.mc.css'), `/* Slim without Bootstrap 4 (sections ${KEEP.join(', ')}) — generated by MiB-Crude */\n${C.keepSections(css, KEEP)}`);
    const dark = path.join(root, 'css', 'slim.one.css');
    if (fs.existsSync(dark)) fs.writeFileSync(path.join(dest, 'css', 'slim.dark.css'), `/* Slim dark skin for [data-bs-theme=dark] — generated by MiB-Crude */\n${C.scope(fs.readFileSync(dark, 'utf8'), '[data-bs-theme=dark]')}`);
    return {
      bootstrap: 4,
      css: ['assets/css/slim.mc.css', ...(fs.existsSync(dark) ? ['assets/css/slim.dark.css'] : []), 'layouts/theme.css'],
      jsFirst: [],
      js: ['layouts/theme.js'],
      providesBootstrap: false, providesJquery: false,
      fonts: 'https://fonts.googleapis.com/css?family=Roboto:300,400,500,700|Montserrat:400,500,600,700',
      options: { menu: variant },
    };
  },
};
