'use strict';
// Project -> PHP application. The generated app is the fixed runtime (runtime/) plus
// configuration arrays and the developer's event code, so regenerating never loses
// hand-written code: that lives in the project (events/, custom/), not in the output.

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const P = require('./project.cjs');
const { TABLE_EVENTS, GLOBAL_EVENTS } = require('./defaults.cjs');

const RUNTIME = path.join(__dirname, '..', 'runtime');

// --- JS value -> PHP literal ---------------------------------------------------

function phpString(s) {
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

function php(value, indent = '') {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'null';
  if (typeof value === 'string') return phpString(value);
  const next = indent + '  ';
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return '[\n' + value.map((v) => next + php(v, next)).join(',\n') + '\n' + indent + ']';
  }
  const keys = Object.keys(value).filter((k) => value[k] !== undefined);
  if (!keys.length) return '[]';
  return '[\n' + keys.map((k) => next + phpString(k) + ' => ' + php(value[k], next)).join(',\n') + '\n' + indent + ']';
}

function phpFile(value, comment) {
  return `<?php\n// ${comment}\n// Generated by MiB-Crude — do not edit: change the project and regenerate.\nreturn ${php(value)};\n`;
}

// --- helpers -------------------------------------------------------------------

function ident(name) {
  const s = String(name).replace(/[^A-Za-z0-9_]/g, '_');
  return /^[0-9]/.test(s) ? '_' + s : s;
}

function copyDir(src, dst, filter = () => true) {
  if (!fs.existsSync(src)) return 0;
  let n = 0;
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name);
    const d = path.join(dst, e.name);
    if (!filter(s, e)) continue;
    if (e.isDirectory()) n += copyDir(s, d, filter);
    else {
      try { if (fs.statSync(d).mtimeMs >= fs.statSync(s).mtimeMs && fs.statSync(d).size === fs.statSync(s).size) continue; } catch { /* missing */ }
      fs.copyFileSync(s, d);
      n++;
    }
  }
  return n;
}

function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  try { if (fs.readFileSync(file, 'utf8') === text) return false; } catch { /* new */ }
  fs.writeFileSync(file, text);
  return true;
}

// pbkdf2 hash understood by the runtime (Security::verifyHash).
function hashPassword(pw) {
  const salt = crypto.randomBytes(12).toString('hex');
  const iter = 120000;
  const hex = crypto.pbkdf2Sync(String(pw), salt, iter, 32, 'sha256').toString('hex');
  return `pbkdf2:sha256:${iter}:${salt}:${hex}`;
}

// Strip "<?php" and comments-only header; keep the user's body as method body.
function eventBody(code) {
  return String(code || '').replace(/^\s*<\?php\s*/, '').replace(/\?>\s*$/, '').trimEnd();
}

function indentCode(code, pad) {
  return code.split('\n').map((l) => (l.trim() ? pad + l : '')).join('\n');
}

function eventClass(className, group, events, extraMethods) {
  const defs = group === '_global' ? GLOBAL_EVENTS : TABLE_EVENTS;
  const methods = [];
  for (const [name, code] of Object.entries(events || {})) {
    const body = eventBody(code);
    if (!body.trim()) continue;
    if (name.startsWith('JS_')) continue; // client-side, emitted as JavaScript
    let args = defs[name] ? defs[name].args : null;
    if (!args && /^Custom_/.test(name)) args = '$params = []';
    if (!args && /^Snippet_/.test(name)) args = '$page';
    if (!args && /^Button_/.test(name)) args = '$params, &$result, $button';
    if (!args && /^Task_/.test(name)) args = '&$message';
    if (args == null) continue; // unknown event name: ignored
    methods.push(`    public function ${ident(name)}(${args})\n    {\n${indentCode(body, '        ')}\n    }`);
  }
  methods.push(...extraMethods);
  return `<?php\n// Events of ${group === '_global' ? 'the application' : `table ${group}`}. Generated by MiB-Crude from the project's events/ folder.\n`
    + `class ${className} extends \\MiB\\Events\n{\n${methods.join('\n\n')}\n}\n`;
}

// --- validation before generating ----------------------------------------------

function check(proj) {
  const problems = [];
  const tableNames = new Set(proj.tables.map((t) => t.name));
  const connIds = new Set(proj.connections.map((c) => c.id));
  if (!proj.connections.length) problems.push({ level: 'error', msg: 'Nessuna connessione al database' });
  if (proj.connections.find((c) => c.id === proj.project.defaultConnection)?.driver === 'rest') problems.push({ level: 'error', msg: 'La connessione principale deve essere un database (utenti, permessi e registro vivono lì), non un servizio REST' });
  if (proj.connections.length && !connIds.has(proj.project.defaultConnection)) problems.push({ level: 'error', msg: `Connessione predefinita "${proj.project.defaultConnection}" inesistente` });
  for (const t of proj.tables) {
    if (!connIds.has(t.connection)) problems.push({ level: 'error', msg: `${t.name}: connessione "${t.connection}" inesistente` });
    if (!t.keys || !t.keys.length) problems.push({ level: 'warning', msg: `${t.name}: nessuna chiave primaria, modifica/eliminazione/visualizzazione disattivate` });
    for (const f of t.fields) {
      const lk = f.editAs && f.editAs.lookup;
      if (lk && lk.kind !== 'list' && ['select', 'radio', 'checkboxes', 'autocomplete'].includes(f.editAs.type)) {
        if (!lk.table) problems.push({ level: 'error', msg: `${t.name}.${f.name}: lookup senza tabella` });
        if (lk.dependsOn && lk.dependsOn.field && !t.fields.some((x) => x.name === lk.dependsOn.field)) problems.push({ level: 'error', msg: `${t.name}.${f.name}: dipende da un campo inesistente "${lk.dependsOn.field}"` });
      }
    }
    for (const d of t.details || []) if (!tableNames.has(d.table)) problems.push({ level: 'warning', msg: `${t.name}: dettaglio "${d.table}" non incluso nel progetto` });
  }
  const sec = proj.security;
  if (sec.enabled && sec.mode === 'database' && !sec.users.managed && (!sec.users.table || !sec.users.usernameField || !sec.users.passwordField)) {
    problems.push({ level: 'error', msg: 'Sicurezza: tabella utenti personalizzata incompleta (tabella, campo utente, campo password)' });
  }
  if (sec.enabled && sec.mode === 'hardcoded' && !sec.hardcoded.passwordHash) problems.push({ level: 'error', msg: 'Sicurezza: imposta la password dell\'utente fisso' });
  if (!sec.enabled && proj.project.settings.api && proj.project.settings.api.enabled) problems.push({ level: 'warning', msg: 'API REST attiva senza login: chiunque raggiunga il sito può leggere e scrivere i dati esposti' });
  for (const kind of ['reports', 'charts']) for (const r of proj[kind] || []) if (!tableNames.has(r.table)) problems.push({ level: 'error', msg: `${kind === 'reports' ? 'Report' : 'Grafico'} ${r.name}: tabella "${r.table}" inesistente` });
  return problems;
}

// --- generation -------------------------------------------------------------------

function buildLang(proj) {
  const out = {};
  const base = JSON.parse(fs.readFileSync(path.join(RUNTIME, 'lang', 'en.json'), 'utf8'));
  for (const code of proj.project.languages) {
    let builtin = base;
    const f = path.join(RUNTIME, 'lang', `${code}.json`);
    if (fs.existsSync(f)) builtin = { ...base, ...JSON.parse(fs.readFileSync(f, 'utf8')) };
    out[code] = { ...builtin, ...((proj.lang || {})[code] || {}) };
  }
  return out;
}

function autoMenu(proj) {
  return proj.tables.filter((t) => t.pages && t.pages.list && t.pages.list.enabled && !t.hideFromMenu).map((t) => ({ type: 'table', table: t.name, page: 'list', icon: t.icon || 'table' }));
}

function generate(proj, opts = {}) {
  const out = opts.outDir || P.outputDir(proj);
  const secrets = opts.secrets || P.readSecrets(proj.dir);
  const problems = check(proj);
  if (problems.some((p) => p.level === 'error') && !opts.force) {
    const e = new Error('Il progetto contiene errori:\n' + problems.filter((p) => p.level === 'error').map((p) => '• ' + p.msg).join('\n'));
    e.problems = problems;
    throw e;
  }
  const started = Date.now();
  fs.mkdirSync(out, { recursive: true });
  const changed = [];
  const w = (rel, text) => { if (write(path.join(out, rel), text)) changed.push(rel); };

  // Runtime and assets.
  let copied = copyDir(path.join(RUNTIME, 'lib'), path.join(out, 'runtime', 'lib'));
  copied += copyDir(path.join(RUNTIME, 'views'), path.join(out, 'runtime', 'views'));
  // DejaVu Sans for the PDF exports (Unicode); without it the PDFs fall back to Helvetica / Windows-1252
  copied += copyDir(path.join(RUNTIME, 'fonts'), path.join(out, 'runtime', 'fonts'));
  w('runtime/bootstrap.php', fs.readFileSync(path.join(RUNTIME, 'bootstrap.php'), 'utf8'));
  w('runtime/classic-route.php', fs.readFileSync(path.join(RUNTIME, 'classic-route.php'), 'utf8'));
  copied += copyDir(path.join(RUNTIME, 'assets'), path.join(out, 'assets'));
  copied += copyDir(path.join(proj.dir, 'custom'), path.join(out, 'custom'));
  // Graphic theme from the local library: assets under theme/<id>/, PHP layouts under runtime/themes/<id>/.
  const installTheme = (packId) => {
    if (!packId) return null;
    const Themes = require('./themes/index.cjs');
    const th = Themes.load(opts.themesDir, packId);
    if (!th) throw new Error(`Il tema grafico "${packId}" non è installato su questo computer: importalo da Impostazioni e stile → Temi grafici`);
    const adapter0 = Themes.ADAPTERS.find((a) => a.id === th.manifest.adapter);
    // packs installed by an older version: files the adapter adds now (e.g. Webarch colours), from the template folder
    if (adapter0 && adapter0.colours) try { adapter0.colours(th.manifest.source, path.join(th.dir, 'assets')); } catch { /* template folder gone */ }
    copied += copyDir(path.join(th.dir, 'assets'), path.join(out, 'theme', packId, 'assets'));
    // Layouts, theme.css and theme.js are MiB-Crude code: taken from the current adapter, so a theme imported
    // with an older version gets every fix without importing the template again (library copy as fallback).
    const adapter = Themes.ADAPTERS.find((a) => a.id === th.manifest.adapter);
    const own = adapter ? path.join(__dirname, 'themes', adapter.dir) : null;
    const layouts = own && fs.existsSync(own) ? own : path.join(th.dir, 'layouts');
    const mine = (s) => /\.(php|css|js)$/.test(s) && !/adapter\.cjs$/.test(s);
    copied += copyDir(layouts, path.join(out, 'theme', packId, 'layouts'), (s) => mine(s) && !s.endsWith('.php'));
    copied += copyDir(layouts, path.join(out, 'runtime', 'themes', packId), (s) => s.endsWith('.php'));
    const m = th.manifest;
    // options each user can change in the app (theme customizer), when the adapter allows it and the project does not turn it off
    const choices = adapter && adapter.choices && (proj.project.theme || {}).userChoices !== false ? adapter.choices(path.join(th.dir, 'assets')) : [];
    return { id: packId, kind: m.kind || 'app', css: m.css, js: m.js, jsFirst: m.jsFirst || [], providesBootstrap: !!m.providesBootstrap, providesJquery: !!m.providesJquery, fonts: m.fonts || '', dark: m.dark || {}, options: m.options || {}, choices };
  };
  const themePack = installTheme(proj.project.theme && proj.project.theme.pack);
  const authPack = installTheme(proj.project.theme && proj.project.theme.authPack);
  // public/: files served from the application root (phpr "source" folder).
  copied += copyDir(path.join(proj.dir, 'public'), out);
  const logo = path.join(proj.dir, 'custom', 'logo.png');
  if (fs.existsSync(logo)) fs.copyFileSync(logo, path.join(out, 'assets', 'logo.png'));

  // Tables.
  const tablesIndex = {};
  const used = new Set();
  const masters = {};
  for (const t of proj.tables) for (const d of t.details || []) (masters[d.table] ||= []).push({ master: t.name, masterKeys: d.masterKeys, detailKeys: d.detailKeys });
  const eventsIndex = {};
  for (const t of proj.tables) {
    let file = ident(t.name).toLowerCase();
    while (used.has(file)) file += '_';
    used.add(file);
    tablesIndex[t.name] = file;
    const def = { ...t, masters: masters[t.name] || [] };
    if (!def.keys || !def.keys.length) {
      def.pages = { ...def.pages, edit: { ...def.pages.edit, enabled: false }, view: { ...def.pages.view, enabled: false }, delete: { ...def.pages.delete, enabled: false } };
    }
    w(`config/tables/${file}.php`, phpFile(def, `Datasource ${t.name}`));
    // Event class: user events + custom "view as" code.
    const extra = [];
    for (const f of t.fields) {
      if (f.viewAs && f.viewAs.type === 'custom' && f.viewAs.code) {
        extra.push(`    public function ViewAs_${ident(f.name)}($value, $row, $context)\n    {\n${indentCode(eventBody(f.viewAs.code), '        ')}\n    }`);
      }
      // PHP expressions (imported from phpr): default value, auto-update value, lookup WHERE.
      if (f.defaultCode) extra.push(`    public function Default_${ident(f.name)}()\n    {\n        return ${f.defaultCode};\n    }`);
      if (f.autoUpdateCode) extra.push(`    public function AutoUpdate_${ident(f.name)}()\n    {\n        return ${f.autoUpdateCode};\n    }`);
      const lk = f.editAs && f.editAs.lookup;
      if (lk && lk.whereCode) extra.push(`    public function LookupWhere_${ident(f.name)}()\n    {\n        return ${lk.whereCode};\n    }`);
    }
    const evs = (proj.events || {})[t.name] || {};
    // Client-side events (phpr "JavaScript OnLoad"): one script per table, compiled in the browser.
    const js = Object.fromEntries(Object.entries(evs).filter(([n, c]) => n.startsWith('JS_OnLoad_') && c && c.trim()).map(([n, c]) => [n.slice('JS_OnLoad_'.length), c]));
    // Custom buttons: client code before/after the server call.
    const btns = {};
    for (const [n, c] of Object.entries(evs)) {
      const m = n.match(/^JS_Button(Before|After)_(\w+)$/);
      if (m && c && c.trim()) (btns[m[2]] ||= {})[m[1].toLowerCase()] = c;
    }
    if (Object.keys(btns).length || (t.buttons && t.buttons.length)) js.__buttons = btns;
    if (Object.keys(js).length) {
      def.jsFile = `js/ev_${file}.js`;
      w(`assets/js/ev_${file}.js`, `// Generated by MiB-Crude: JavaScript events of ${t.name}\nwindow.MCJS = window.MCJS || {};\nwindow.MCJS[${JSON.stringify(t.name)}] = ${JSON.stringify(js, null, 1)};\n`);
      w(`config/tables/${file}.php`, phpFile(def, `Datasource ${t.name}`));
    }
    if (Object.values(evs).some((c) => eventBody(c).trim()) || extra.length) {
      // Method names come from field names: avoid duplicates after sanitizing.
      const seen = new Set();
      for (let i = extra.length - 1; i >= 0; i--) { const m = extra[i].match(/function (\w+)\(/)[1]; if (seen.has(m)) extra.splice(i, 1); else seen.add(m); }
      const cls = 'Ev_' + file;
      eventsIndex[t.name] = cls;
      w(`events/${cls}.php`, eventClass(cls, t.name, evs, extra));
    }
  }
  const gev = (proj.events || {})._global || {};
  if (Object.values(gev).some((c) => eventBody(c).trim())) {
    eventsIndex._global = 'Ev__global';
    w('events/Ev__global.php', eventClass('Ev__global', '_global', gev, []));
  }
  // Remove stale generated files of deleted tables/events.
  for (const dir of ['config/tables', 'events']) {
    const keep = new Set(dir === 'events' ? Object.values(eventsIndex).map((c) => `${c}.php`) : Object.values(tablesIndex).map((f) => `${f}.php`));
    try { for (const f of fs.readdirSync(path.join(out, dir))) if (f.endsWith('.php') && !keep.has(f)) fs.unlinkSync(path.join(out, dir, f)); } catch { /* none */ }
  }

  // Security (without secrets).
  const sec = JSON.parse(JSON.stringify(proj.security));
  for (const p of sec.providers.oidc || []) delete p.clientSecret;
  if (sec.providers.ldap) delete sec.providers.ldap.bindPassword;

  const connections = {};
  for (const c of proj.connections) {
    const { id, driver, host, port, database, user, schema, file } = c;
    connections[id] = { driver, host: host || '', port: port || '', database: database || '', user: user || '', schema: schema || '', file: file || '' };
    if (driver === 'rest') Object.assign(connections[id], { url: c.url || '', auth: c.auth || 'none' });
  }
  const byName = (list) => Object.fromEntries((list || []).map((x) => [x.name, x]));
  const settings = { ...proj.project.settings };
  // Header / footer / menu of the project: code goes to custom/regions/<name>.php, the config keeps the rest.
  if (settings.regions) {
    settings.regions = Object.fromEntries(Object.entries(settings.regions).map(([name, r]) => {
      const { code, ...rest } = r || {};
      // the guard stops a direct request when the web server does not apply custom/.htaccess
      if (rest.source === 'code') w(`custom/regions/${name}.php`, `<?php if (!class_exists('MiB\\\\Regions', false)) { http_response_code(404); exit; } ?>\n${code || ''}`);
      return [name, rest];
    }));
  }
  const app = {
    generator: 'MiB-Crude',
    generatedAt: new Date().toISOString(),
    title: proj.project.title,
    languages: proj.project.languages,
    defaultLanguage: proj.project.defaultLanguage,
    defaultConnection: proj.project.defaultConnection,
    connections,
    settings,
    theme: { ...proj.project.theme, pack: themePack, authPack },
    security: sec,
    menu: proj.menu.items && proj.menu.items.length ? proj.menu.items : autoMenu(proj),
    tables: tablesIndex,
    events: eventsIndex,
    reports: byName(proj.reports),
    charts: byName(proj.charts),
    dashboards: byName(proj.dashboards),
    mail: proj.project.mail || {},
    debug: !!opts.debug,
    systemPrefix: proj.project.systemPrefix || 'mc_',
    // phpr short names (orders → orders_list.php) for the NTLM permission pages
    tableShort: Object.fromEntries(proj.tables.filter((t) => t.phprShort).map((t) => [t.name, String(t.phprShort).toLowerCase().replace(/[^a-z0-9_]/g, '_')])),
  };
  w('config/app.php', phpFile(app, 'Application configuration'));
  const sc = { connections: {}, oidc: {}, mail: {} };
  for (const c of proj.connections) sc.connections[c.id] = { password: (secrets.connections || {})[c.id] || '' };
  for (const p of proj.security.providers.oidc || []) sc.oidc[p.id] = (secrets.oidc || {})[p.id] || '';
  sc.mail.password = secrets.mailPassword || '';
  sc.sms = { password: secrets.smsPassword || '' };
  sc.geocode = { key: secrets.geocodeKey || '' };
  sc.encryptionKey = secrets.encryptionKey || '';
  w('config/secrets.php', phpFile(sc, 'Passwords. Keep this file out of version control and readable only by the web server.'));

  for (const [code, dict] of Object.entries(buildLang(proj))) w(`lang/${code}.php`, phpFile(dict, `Strings (${code})`));

  // Entry point and web server protection.
  w('index.php', "<?php\nrequire __DIR__ . '/runtime/bootstrap.php';\n\\MiB\\App::run(__DIR__);\n");
  // Installable app: service worker at the root (its scope is the folder it is served from).
  if (settings.pwa) w('sw.js', fs.readFileSync(path.join(RUNTIME, 'pwa-sw.js'), 'utf8'));
  // Scheduled tasks (settings.tasks): the system runs it every minute; never from the web.
  w('cron.php', "<?php\n// Scheduled tasks of the application: run every minute with php cron.php (crontab, Windows Task Scheduler).\n// php cron.php --list shows them, php cron.php --run NAME runs one now. Generated by MiB-Crude.\nif (PHP_SAPI !== 'cli') { http_response_code(404); exit; }\nrequire __DIR__ . '/runtime/bootstrap.php';\nexit(\\MiB\\Tasks::cli(__DIR__, array_slice($argv, 1)));\n");
  // classic-style URLs (orders_list.php, orders_edit.php?editid1=5) for imported projects.
  if (settings.classicUrls) {
    const pages = ['list', 'add', 'edit', 'view', 'search', 'print', 'export', 'import'];
    for (const t of proj.tables) {
      const short = String(t.phprShort || t.name).toLowerCase().replace(/[^a-z0-9_]/g, '_');
      for (const pg of pages) {
        w(`${short}_${pg}.php`, `<?php\n// classic-compatible entry point. Generated by MiB-Crude.\n$mcRoute = ${php({ p: pg, t: t.name, keys: t.keys || [] })};\nrequire __DIR__ . '/runtime/classic-route.php';\n`);
      }
    }
    for (const [f, pg] of [['menu.php', 'home'], ['login.php', 'login'], ['logout.php', 'logout'], ['changepwd.php', 'profile'], ['register.php', 'register'], ['remind.php', 'forgot']]) {
      w(f, `<?php\n$mcRoute = ${php({ p: pg, t: '', keys: [] })};\nrequire __DIR__ . '/runtime/classic-route.php';\n`);
    }
  }
  const deny = 'Require all denied\n<IfModule !mod_authz_core.c>\nDeny from all\n</IfModule>\n';
  for (const d of ['config', 'runtime', 'events', 'lang']) w(`${d}/.htaccess`, deny);
  w('custom/.htaccess', '<FilesMatch "\\.php$">\nRequire all denied\n</FilesMatch>\n');
  const upload = settings.uploadDir || 'files';
  if (!path.isAbsolute(upload)) {
    fs.mkdirSync(path.join(out, upload), { recursive: true });
    w(`${upload}/.htaccess`, deny);
  }
  w('.htaccess', 'Options -Indexes\nDirectoryIndex index.php\n<FilesMatch "\\.(json|md|lock|log)$">\nRequire all denied\n</FilesMatch>\n');
  w('web.config', '<?xml version="1.0" encoding="UTF-8"?>\n<configuration><system.webServer><defaultDocument><files><add value="index.php"/></files></defaultDocument>'
    + '<security><requestFiltering><hiddenSegments><add segment="config"/><add segment="runtime"/><add segment="events"/><add segment="lang"/><add segment="' + upload + '"/></hiddenSegments></requestFiltering></security></system.webServer></configuration>\n');
  w('nginx.conf.example', `# nginx: protect internal folders\nlocation ~ ^/(config|runtime|events|lang|${upload})/ { deny all; }\nlocation ~ ^/custom/.*\\.php$ { deny all; }\n`);

  return { outDir: out, changed, copied, problems, ms: Date.now() - started };
}

// php -l on generated PHP (events and config). Returns [{file, error}].
function lint(outDir, phpBin = 'php') {
  const errors = [];
  for (const dir of ['events', 'config', 'config/tables']) {
    let files = [];
    try { files = fs.readdirSync(path.join(outDir, dir)).filter((f) => f.endsWith('.php')); } catch { continue; }
    for (const f of files) {
      try { execFileSync(phpBin, ['-l', path.join(outDir, dir, f)], { stdio: 'pipe' }); } catch (e) {
        errors.push({ file: `${dir}/${f}`, error: String(e.stdout || e.stderr || e.message).replace(/\n+/g, ' ').trim() });
      }
    }
  }
  return errors;
}

